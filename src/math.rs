#[doc(hidden)]
mod __hidden {
    pub trait Sealed {}
}

/// # Safety
/// The value represented by this type must be a power of two.
pub unsafe trait PowerOfTwo: __hidden::Sealed {}

macro_rules! impl_traits {
    ($name: ident, $ty: ty, [$($pow2: expr),*$(,)?]) => {
        pub struct $name<const V: $ty>;

        impl<const V: $ty> __hidden::Sealed for $name<V> {}
        $(
            // SAFETY: The value is a power of two
            unsafe impl PowerOfTwo for $name<{$pow2}> {}
        )*
    };
}

